def _crop(lines: tuple[str, ...]) -> tuple[str, ...]:
    """Drop the blank margins (spaces, U+2800) shared by all lines so centering uses the visible ink."""
    blank = " ⠀"
    lines = tuple(line.rstrip(blank) for line in lines)
    left = min((len(line) - len(line.lstrip(blank)) for line in lines if line), default=0)
    return tuple(line[left:] for line in lines)


def _centered(lines: tuple[str, ...], columns: int) -> list[str]:
    lines = _crop(lines)
    width = max(len(line) for line in lines)
    return [line.ljust(width).center(columns).rstrip() for line in lines]


def banner(*, color: bool = False) -> str:
    """Art, title, then version and tagline, centered (no padding if the terminal is too narrow).

    With `color`: the art fades from Neptune blue to violet top to bottom, the title left to right.
    Centering is done on the plain text first, so the colored banner has the same layout."""
    on = theme.color_enabled(color)
    columns = shutil.get_terminal_size((80, 24)).columns
    art_fits = columns >= max(len(line) for line in _ART)  # wrapped braille is unreadable
    art = _centered(_ART, columns) if art_fits else []
    title = _centered(_TITLE, columns)
    version = f"v{__version__}".center(columns).rstrip()
    tagline = "Passive attack-surface mapper".center(columns).rstrip()
    if on:
        art = theme.vertical_gradient(art, theme.NEPTUNE, theme.VIOLET)
        title = [theme.gradient(line, theme.NEPTUNE, theme.VIOLET) for line in title]
        version = theme.paint(version, theme.MUTED)
        tagline = theme.paint(tagline, theme.LAVENDER)
    return "\n".join([*art, *title, "", version, tagline]) + "\n"
